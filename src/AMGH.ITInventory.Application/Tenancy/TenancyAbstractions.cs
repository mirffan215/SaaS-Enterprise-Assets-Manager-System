using AMGH.ITInventory.Shared.Abstractions;
using AMGH.ITInventory.Shared.Results;

namespace AMGH.ITInventory.Application.Tenancy;

/// <summary>Settings for database-per-tenant operation (appsettings.json "Tenancy").</summary>
public sealed class TenancyOptions
{
    public const string SectionName = "Tenancy";

    /// <summary>Turns multi-tenant mode on. Needs the connection string "TenantCatalog".</summary>
    public bool Enabled { get; set; }

    /// <summary>Host suffix for sub-domain resolution: with "example.com", acme.example.com is tenant "acme".</summary>
    public string? BaseDomain { get; set; }

    /// <summary>Allows <c>?tenant=code</c> to pick the tenant (local development only).</summary>
    public bool AllowQueryParameter { get; set; }

    /// <summary>Privileged SQL Server connection (CREATE DATABASE rights), used only for provisioning.</summary>
    public string? ServerConnectionString { get; set; }

    /// <summary>
    /// Connection string the application uses at run time for each tenant database; "{database}" is replaced by the
    /// database name. Empty: the provisioning connection string with the database name replaced.
    /// </summary>
    public string? TenantConnectionTemplate { get; set; }

    /// <summary>Folder with the deployment scripts (relative to the application folder).</summary>
    public string ScriptsPath { get; set; } = "SQLScripts";

    /// <summary>Master-key password for the tenant's column encryption; random per tenant when empty.</summary>
    public string? MasterKeyPassword { get; set; }

    /// <summary>Application database login granted access by script 08; the script is skipped when empty.</summary>
    public string? AppLogin { get; set; }

    /// <summary>
    /// Secret for the operator page (/Tenant/Admin) where the operator of the installation creates customer companies.
    /// The page does not exist while this is empty. Generated by Install-SaaS.ps1.
    /// </summary>
    public string? OperatorKey { get; set; }

    /// <summary>
    /// False (default): a company administrator creates a full data export and downloads it straight away (password-protected archive,
    /// one-time download, every step audited). True: a second administrator must approve each export first (dual control).
    /// </summary>
    public bool ExportRequiresApproval { get; set; }

    /// <summary>
    /// False (default): only the operator creates companies (page /Tenant/Admin, protected by the operator key).
    /// True: anyone who can reach the site may register a company (page /Register; limited to a few per address and hour).
    /// Turn it on only for a service that is meant to take sign-ups.
    /// </summary>
    public bool AllowSelfRegistration { get; set; }

    /// <summary>
    /// False (default): people choose their company first (company code, remembered afterwards, or the company's own address).
    /// True: the sign-in page asks only for user name or e-mail and password and finds the company itself (searches every company, up to 100).
    /// </summary>
    public bool GlobalSignIn { get; set; }

    /// <summary>
    /// Folder for company backups (made by the operator page or Backup-SaaS.ps1). The SQL Server service must be able to write to it and the
    /// application pool to list it. Empty: the instance's default backup folder (then the page can back up and restore, but not list files).
    /// </summary>
    public string? BackupFolder { get; set; }

    /// <summary>True (default): when the application starts, every company database is brought up to the installed version's schema (a backup is made first when something has to change).</summary>
    public bool AutoUpgrade { get; set; } = true;

    /// <summary>
    /// Off-site copy of every scheduled backup, as a password-protected zip: a folder on another machine (UNC path such as \\nas\eams) or a synced folder.
    /// Empty: no folder copy. The application pool identity needs Modify rights on it. Requires <see cref="OffsitePassword"/>.
    /// </summary>
    public string? OffsiteFolder { get; set; }

    /// <summary>
    /// Off-site copy to Azure Blob Storage: a container SAS URL with create/write/list rights
    /// (https://account.blob.core.windows.net/container?sv=...&amp;sig=...). Empty: none. Requires <see cref="OffsitePassword"/>.
    /// </summary>
    public string? OffsiteBlobUrl { get; set; }

    /// <summary>Password of the off-site zips (generated by Set-OperatorAccess.ps1). Keep a copy in your password vault: without it an off-site copy cannot be opened.</summary>
    public string? OffsitePassword { get; set; }

    /// <summary>Optional https address that receives a JSON message {"text": "..."} when a scheduled backup, its check or its off-site copy fails (Slack, Teams and similar incoming webhooks).</summary>
    public string? AlertWebhookUrl { get; set; }

    /// <summary>Code of the sandbox tenant.</summary>
    public const string DemoCode = "demo";

    /// <summary>Creates the sandbox tenant "demo" (with sample data) at start-up when it is missing, and offers "Explore Demo Environment" on the sign-in page.</summary>
    public bool DemoEnabled { get; set; }

    /// <summary>Password of the demo administrator ("admin"); the demo tenant is not created without it.</summary>
    public string? DemoAdminPassword { get; set; }

    /// <summary>Off by default. Turn on only for a public sandbox: shows the demo user name and password on the demo sign-in page (they open fictitious data only).</summary>
    public bool ShowDemoCredentials { get; set; }
}

/// <summary>A row of the central tenant catalog.</summary>
public sealed record TenantRecord(int Id, string Code, string Name, string ConnectionString, bool IsDemo, bool IsActive, DateTime CreatedAtUtc)
{
    public TenantInfo ToInfo() => new(Id, Code, Name, ConnectionString, IsDemo);
}

/// <summary>Reads and writes the central tenant catalog (one database listing all customers).</summary>
public interface ITenantCatalog
{
    /// <summary>The active tenant with this code (case-insensitive), or null.</summary>
    Task<TenantInfo?> FindActiveAsync(string code, CancellationToken cancellationToken = default);

    Task<bool> ExistsAsync(string code, CancellationToken cancellationToken = default);

    Task<IReadOnlyList<TenantRecord>> ListAsync(CancellationToken cancellationToken = default);

    Task<TenantRecord> AddAsync(string code, string name, string connectionString, bool isDemo, CancellationToken cancellationToken = default);
}

/// <summary>One entry of the operator's activity log (who did what to which company).</summary>
public sealed record TenantEvent(long Id, DateTime AtUtc, string? Code, string Action, string? Detail, string Actor);

/// <summary>Operator actions on the catalog: suspend / resume a company and the log of what the operator did.</summary>
public interface ITenantAdminStore
{
    /// <summary>Suspends (false) or resumes (true) a company; false when the code is unknown. A suspended company cannot be reached by anyone until resumed; its data is untouched.</summary>
    Task<bool> SetActiveAsync(string code, bool active, CancellationToken cancellationToken = default);

    /// <summary>True when the company exists but is suspended.</summary>
    Task<bool> IsSuspendedAsync(string code, CancellationToken cancellationToken = default);

    Task RecordEventAsync(string? code, string action, string? detail, string actor, CancellationToken cancellationToken = default);

    Task<IReadOnlyList<TenantEvent>> RecentEventsAsync(int take, CancellationToken cancellationToken = default);
}

/// <summary>What one company uses (read with the provisioning login; does not touch company data).</summary>
public sealed record TenantUsage(string Code, long DatabaseBytes, int Users, int ActiveUsers, int Assets, DateTime? LastSignInUtc, DateTime? LastChangeUtc, string? Problem);

public interface ITenantUsageService
{
    /// <summary>Usage of every company; one that cannot be read carries a <see cref="TenantUsage.Problem"/>.</summary>
    Task<IReadOnlyList<TenantUsage>> GetAsync(CancellationToken cancellationToken = default);
}

/// <summary>Hashes the first administrator's password in the application's own format, after the password policy.</summary>
public interface ITenantAdminPasswordHasher
{
    /// <summary>The hash, or the unmet password requirements.</summary>
    Result<string> HashNew(string username, string email, string password);
}

/// <summary>Creates a tenant: its own database, schema, seed data, administrator and catalog entry.</summary>
public interface ITenantProvisioningService
{
    /// <param name="companyCode">2 to 10 letters or digits; also the suffix of the database name.</param>
    /// <param name="companyName">Display name of the company.</param>
    /// <param name="adminEmail">E-mail of the first administrator (the user name is "admin").</param>
    /// <param name="adminPassword">Initial password of that administrator; must satisfy the password policy.</param>
    /// <param name="isDemo">Marks the sandbox tenant and loads its sample data.</param>
    /// <param name="cancellationToken">Cancellation of the whole operation.</param>
    /// <param name="includeErrorDetail">Add the technical reason (first line of the database error) to a failure; only for the operator, never for the public.</param>
    Task<Result<TenantInfo>> ProvisionTenantAsync(string companyCode, string companyName, string adminEmail, string adminPassword,
        bool isDemo = false, bool includeErrorDetail = false, CancellationToken cancellationToken = default);
}
